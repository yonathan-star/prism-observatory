def unit(a):return a/np.linalg.norm(a,axis=-1,keepdims=True)
def line(a,b,n=30):
 a=np.array(a);b=np.array(b);t=np.linspace(0,1,n+1)[:,None]
 return a+(b-a)*t,np.tile(unit(b-a),(n+1,1))
def arc(c,r,a,b,n=90):
 v=np.deg2rad(np.linspace(a,b,n+1));sign=np.sign(b-a)
 return np.array(c)+r*np.c_[np.cos(v),np.sin(v)],sign*np.c_[-np.sin(v),np.cos(v)]
def bezier(p,n=90):
 p=np.array(p);t=np.linspace(0,1,n+1)[:,None]
 q=(1-t)**3*p[0]+3*(1-t)**2*t*p[1]+3*(1-t)*t*t*p[2]+t**3*p[3]
 v=3*((1-t)**2*(p[1]-p[0])+2*(1-t)*t*(p[2]-p[1])+t*t*(p[3]-p[2]))
 return q,unit(v)
def joined(parts):
 pp=[];tt=[]
 for p,t in parts:
  if pp:
   assert np.linalg.norm(pp[-1][-1]-p[0])<1e-6
   assert np.linalg.norm(tt[-1][-1]-t[0])<1e-6
  take=slice(None) if not pp else slice(1,None);pp.append(p[take]);tt.append(t[take])
 p=np.concatenate(pp);t=np.concatenate(tt);s=np.r_[0,np.linalg.norm(np.diff(p,axis=0),axis=1).cumsum()]
 return p,t,s
def hermite(s,z0,z1,g0,g1):
 u=s/s[-1];L=s[-1]
 return (2*u**3-3*u*u+1)*z0+(u**3-2*u*u+u)*L*(-g0)+(-2*u**3+3*u*u)*z1+(u**3-u*u)*L*(-g1)
def merge_floor(xy):
 xy=np.asarray(xy);return 78+.08*(xy[...,0]-72)+.005*(xy[...,1]-68)**2
def make_route(name,parts,z0,z1,g0=None,g1=None,merge_handoff=None):
 p,t,s=joined(parts)
 if merge_handoff is not None:
  index=np.flatnonzero(merge_handoff(p))[0];target=merge_floor(p[index]);grad=np.array([.08,.01*(p[index,1]-68)])
  z=np.r_[hermite(s[:index+1],z0,target,g0,-grad@t[index]),merge_floor(p[index+1:])]
 elif g0 is None:z=np.linspace(z0,z1,len(s)) if False else z0+(z1-z0)*s/s[-1]
 else:z=hermite(s,z0,z1,g0,g1)
 assert np.all(np.diff(z)<1e-7),(name,np.diff(z).max())
 return {'name':name,'points':np.c_[p,z],'tangents':t,'stations':s}
