def scad(a):
 if isinstance(a,str):return json.dumps(a)
 if np.isscalar(a):return f'{float(a):.9f}'
 return '['+','.join(scad(v) for v in a)+']'
def export():
 rr=routes();out='// Generated by tools/machine_geometry.py. Original geometry.\n'
 for name,value in [('selector_xy',O),('selector_floor',ROTOR_Z),('tipper_xyz',TIP),('funnel_xy',F),('cascade_xyz',CASCADE),('funnel_pegs',PEGS_F),('cascade_pegs',PEGS_C)]:out+=name+'='+scad(value)+';\n'
